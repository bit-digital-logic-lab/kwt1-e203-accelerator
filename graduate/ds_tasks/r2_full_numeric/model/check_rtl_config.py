#!/usr/bin/env python3
"""r2_full_numeric -- compare the assembled encoder RTL constants with the
round-1 frozen 12-layer numeric asset (layer 0).

The assembled RTL (`graduate/rtl/encoder/`, single-layer `tb_encoder`) carries
constant headers that were generated by an *older* per-sample calibration:

    third_party/attn_params.svh        (KC, SH_KC, RQ, RK, RV, RC, RO)
    third_party/kwt_postnorm_cfg.svh   (MA1, MB1, EPS_Q1, MO1, MGN, MC2,
                                        EPS_Q2, MO2)
    tb_encoder.sv                      (M_A)

The round-1 frozen pack that this task evaluates lives in
`encoder_12numeric/frozen_12layer_calib.json`, layer 0.  If the two disagree,
the assembled RTL cannot be the executable form of the frozen numeric chain
without regenerating the constants (the round-1 `encoder_12numeric` work had to
generate per-layer headers for exactly this reason).

This is the RTL-side "configuration conflict" check.  It is static: no
simulation is claimed.  Exit 2 when any compared constant differs.

Usage:
    python3 model/check_rtl_config.py
"""

from __future__ import annotations

import hashlib
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
TASK = HERE.parent
REPO = HERE.parents[3]

ATTN_SVH = REPO / "graduate/rtl/encoder/third_party/attn_params.svh"
CFG_SVH = REPO / "graduate/rtl/encoder/third_party/kwt_postnorm_cfg.svh"
TB_SV = REPO / "graduate/encoder/tb/tb_encoder.sv"
FROZEN = Path("/home/yang/kwt-worktrees/ds-grad-encoder_12numeric/"
              "graduate/ds_tasks/encoder_12numeric/frozen_12layer_calib.json")


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with Path(path).open("rb") as fh:
        for b in iter(lambda: fh.read(1 << 20), b""):
            h.update(b)
    return h.hexdigest()


def parse_localparams(text: str) -> dict:
    out = {}
    for m in re.finditer(r"localparam\s+(?:integer|int|logic\s+signed\s*\[[^\]]+\])\s+"
                         r"([A-Za-z_][A-Za-z0-9_]*)\s*=\s*"
                         r"(?:32'sd|48'sd|)(-?\d+)", text):
        out[m.group(1)] = int(m.group(2))
    return out


def main():
    lines = []

    def log(m):
        print(m, flush=True)
        lines.append(m)

    frozen = json.loads(FROZEN.read_text())
    L0 = frozen["layers"][0]
    ap = L0["attn_params"]
    coeff = L0["coeff"]
    expected = {
        "KC": ap["KC"], "SH_KC": ap["SH_KC"], "RQ": ap["RQ"], "RK": ap["RK"],
        "RV": ap["RV"], "RC": ap["RC"], "RO": ap["RO"], "M_A": L0["M_A"],
        "MA1": coeff["ma1"], "MB1": coeff["mb1"], "EPS_Q1": coeff["eps_q1"],
        "MO1": coeff["mo1"], "MGN": coeff["mgn"], "MC2": coeff["ma2"],
        "EPS_Q2": coeff["eps_q2"], "MO2": coeff["mo2"],
    }

    src = {}
    src.update(parse_localparams(ATTN_SVH.read_text()))
    src.update(parse_localparams(CFG_SVH.read_text()))
    tb_text = TB_SV.read_text()
    m = re.search(r"\.M_A\s*\(\s*(\d+)\s*\)", tb_text)
    if m:
        src["M_A"] = int(m.group(1))

    log("TASK r2_full_numeric: assembled-RTL vs round-1 frozen layer-0 constants")
    log(f"ASSET frozen {FROZEN} sha256={sha256(FROZEN)}")
    log(f"ASSET attn_params.svh sha256={sha256(ATTN_SVH)}")
    log(f"ASSET kwt_postnorm_cfg.svh sha256={sha256(CFG_SVH)}")
    log(f"ASSET tb_encoder.sv sha256={sha256(TB_SV)}")

    mismatches = []
    for name in ("KC", "SH_KC", "RQ", "RK", "RV", "RC", "RO", "M_A",
                 "MA1", "MB1", "EPS_Q1", "MO1", "MGN", "MC2", "EPS_Q2", "MO2"):
        rtl = src.get(name)
        fz = expected[name]
        ok = rtl == fz
        log(f"COMPARE {name:8s} rtl={rtl} frozen={fz} {'OK' if ok else 'MISMATCH'}")
        if not ok:
            mismatches.append({"name": name, "rtl": rtl, "frozen": fz})

    result = {
        "task": "r2_full_numeric",
        "state": "RTL_CONFIG_CONFLICT" if mismatches else "RTL_CONFIG_MATCH",
        "evidence_level": "static constant comparison (no simulation)",
        "assets": {
            "frozen_12layer_calib.json": {"path": str(FROZEN), "sha256": sha256(FROZEN)},
            "attn_params.svh": {"path": str(ATTN_SVH), "sha256": sha256(ATTN_SVH)},
            "kwt_postnorm_cfg.svh": {"path": str(CFG_SVH), "sha256": sha256(CFG_SVH)},
            "tb_encoder.sv": {"path": str(TB_SV), "sha256": sha256(TB_SV)},
        },
        "mismatches": mismatches,
        "mismatch_count": len(mismatches),
    }
    (TASK / "rtl_config.json").write_text(json.dumps(result, indent=2) + "\n")
    (TASK / "logs").mkdir(exist_ok=True)
    (TASK / "logs" / "check_rtl_config.log").write_text("\n".join(lines) + "\n")
    return 2 if mismatches else 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except SystemExit:
        raise
    except Exception as exc:
        print(f"RUNTIME_FAIL {type(exc).__name__}: {exc}", file=sys.stderr)
        raise SystemExit(1)
