#!/usr/bin/env python3
"""Emit per-layer SystemVerilog configuration + hex stimulus for the RTL chain.

For every encoder layer this writes an include directory
(``<build>/layer_XX/include/{attn_params.svh,kwt_postnorm_cfg.svh}``) and a
vector directory (``<build>/layer_XX/vectors/*.hex``).  All numbers come from
the frozen calibration produced by ``model/run_l1.py``; nothing is read from an
RTL dump.
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np

D, HID, T = 64, 256, 99
QB = 16
GAMMA_FRAC = 16
GOUT_FRAC = 16
ISQ_FRAC = 16
VAR_FRAC = 16
QG = 28
QGN = 16
GELU_FRAC = 8
LUT_STEP = 16
LUT_N = 257
ISQ_MAX = (1 << 24) - 1
CLAMP_A = 2047


def hx(v, width):
    return f"{int(v) & ((1 << width) - 1):0{width // 4}x}"


def write_hex(path: Path, values, width):
    with Path(path).open("w") as fh:
        for v in np.asarray(values).ravel():
            fh.write(hx(v, width) + "\n")


def _func(name, values, width):
    fmt = {64: "64'sd", 32: "32'sd", 16: "16'sd"}[width]
    lines = [f"function automatic logic signed [{width - 1}:0] {name}(input int unsigned i);\n",
             "    case (i)\n"]
    for i, v in enumerate(values):
        lit = f"-{fmt}{abs(int(v))}" if int(v) < 0 else f"{fmt}{int(v)}"
        lines.append(f"        {len(values)}'d{i}: {name} = {lit};\n")
    lines.append(f"        default: {name} = {width}'sd0;\n")
    lines.append("    endcase\nendfunction\n")
    return "".join(lines)


def emit_attn_params(params: dict) -> str:
    return (
        "// AUTO-GENERATED by model/gen_rtl_vectors.py -- do not edit.\n"
        "localparam int ATT_T     = %d;\n"
        "localparam int ATT_D     = %d;\n"
        "localparam int F_BITS    = %d;\n"
        "localparam int M_LUT     = %d;\n"
        "localparam int G_SH      = %d;\n"
        "localparam int KC        = %d;\n"
        "localparam int SH_KC     = %d;\n"
        "localparam int RQ        = %d;\n"
        "localparam int RK        = %d;\n"
        "localparam int RV        = %d;\n"
        "localparam int RC        = %d;\n"
        "localparam int RO        = %d;\n"
        % (T, D, params["F_BITS"], params["M_LUT"], params["G_SH"], params["KC"],
           params["SH_KC"], params["RQ"], params["RK"], params["RV"],
           params["RC"], params["RO"]))


def emit_postnorm_cfg(layer: dict, gelu_lut) -> str:
    c = layer["coeff"]
    sc = layer["scales"]
    cfg = []
    cfg.append("// AUTO-GENERATED by model/gen_rtl_vectors.py -- do not edit.\n")
    cfg.append(f"// KWT-1 encoder layer {layer['layer']} PostNorm coefficients.\n")
    cfg.append("// No include guard: include once per module scope.\n")
    for k, v in (("D", D), ("HID", HID), ("CLAMP_A", CLAMP_A), ("QB", QB),
                 ("GAMMA_FRAC", GAMMA_FRAC), ("GOUT_FRAC", GOUT_FRAC),
                 ("ISQ_FRAC", ISQ_FRAC), ("VAR_FRAC", VAR_FRAC), ("QG", QG),
                 ("QGN", QGN), ("GELU_FRAC", GELU_FRAC), ("LUT_STEP", LUT_STEP),
                 ("LUT_N", LUT_N), ("ISQ_MAX", ISQ_MAX)):
        cfg.append(f"localparam integer {k} = {v};\n")
    cfg.append(f"localparam logic signed [47:0] EPS_Q1 = 48'sd{int(c['eps_q1'])};\n")
    cfg.append(f"localparam logic signed [47:0] EPS_Q2 = 48'sd{int(c['eps_q2'])};\n")
    cfg.append(f"localparam logic signed [31:0] MA1 = 32'sd{int(c['ma1'])};\n")
    cfg.append(f"localparam logic signed [31:0] MB1 = 32'sd{int(c['mb1'])};\n")
    cfg.append(f"localparam logic signed [31:0] MGN = 32'sd{int(c['mgn'])};\n")
    cfg.append(f"localparam logic signed [31:0] MO1 = 32'sd{int(c['mo1'])};\n")
    cfg.append(f"localparam logic signed [31:0] MC2 = 32'sd{int(c['ma2'])};\n")
    cfg.append(f"localparam logic signed [31:0] MO2 = 32'sd{int(c['mo2'])};\n")
    cfg.append(_func("MG_F", [int(v) for v in c["mg"]], 32))
    cfg.append(_func("G1F_F", [int(v) for v in c["g1f"]], 32))
    cfg.append(_func("B1F_F", [int(v) for v in c["b1f"]], 32))
    cfg.append(_func("G2F_F", [int(v) for v in c["g2f"]], 32))
    cfg.append(_func("B2F_F", [int(v) for v in c["b2f"]], 32))
    cfg.append(_func("MD2_F", [int(v) for v in c["md2"]], 32))
    cfg.append(_func("GELU_LUT_F", [int(v) for v in gelu_lut], 16))
    return "".join(cfg)


def write_layer(layer_dir: Path, layer: dict, calib: dict, X_int: np.ndarray) -> dict:
    layer_dir = Path(layer_dir)
    inc = layer_dir / "include"
    vec = layer_dir / "vectors"
    inc.mkdir(parents=True, exist_ok=True)
    vec.mkdir(parents=True, exist_ok=True)

    (inc / "attn_params.svh").write_text(emit_attn_params(layer["attn"]["params"]))
    (inc / "kwt_postnorm_cfg.svh").write_text(
        emit_postnorm_cfg(layer, calib["lut"]))

    attn_lut = np.asarray(calib["attn_lut"], dtype=np.int64)
    w1 = np.asarray(layer["ffn1"]["w"], dtype=np.int64)        # (D,HID) [j][c]
    b1 = np.asarray(layer["ffn1"]["b"], dtype=np.int64)        # (HID,)
    w2 = np.asarray(layer["ffn2"]["w"], dtype=np.int64)        # (HID,D) [j][k]
    b2 = np.asarray(layer["ffn2"]["b"], dtype=np.int64)        # (D,)

    write_hex(vec / "sel0_x.hex", X_int, 16)
    write_hex(vec / "sel1_wq.hex", np.asarray(layer["attn"]["wq"]), 16)
    write_hex(vec / "sel2_wk.hex", np.asarray(layer["attn"]["wk"]), 16)
    write_hex(vec / "sel3_wv.hex", np.asarray(layer["attn"]["wv"]), 16)
    write_hex(vec / "sel4_wo.hex", np.asarray(layer["attn"]["wo"]), 16)
    write_hex(vec / "sel5_bias.hex", np.asarray(layer["attn"]["bias"]), 32)
    write_hex(vec / "sel6_lut.hex", attn_lut, 16)
    write_hex(vec / "sel7_w1.hex", w1.T.reshape(-1), 16)       # index c*D+j
    write_hex(vec / "sel8_b1.hex", b1, 32)
    write_hex(vec / "sel9_w2.hex", w2.T.reshape(-1), 16)       # index k*HID+j
    write_hex(vec / "sel10_b2.hex", b2, 32)

    meta = dict(layer=layer["layer"], M_A=int(layer["M_A"]), Q_A=16, T=T, D=D, HID=HID,
                scales=layer["scales"], attn_params=layer["attn"]["params"])
    (vec / "meta.json").write_text(json.dumps(meta, indent=2) + "\n")
    return meta
